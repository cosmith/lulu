package com.cosmith.lulu.core.fsrs

import kotlinx.serialization.json.Json
import kotlinx.serialization.json.JsonObject
import kotlinx.serialization.json.double
import kotlinx.serialization.json.int
import kotlinx.serialization.json.intOrNull
import kotlinx.serialization.json.jsonArray
import kotlinx.serialization.json.jsonObject
import kotlinx.serialization.json.jsonPrimitive
import kotlinx.serialization.json.long
import java.time.Duration
import java.time.Instant
import java.time.temporal.ChronoUnit
import kotlin.math.abs
import kotlin.test.Test
import kotlin.test.assertEquals
import kotlin.test.assertTrue
import kotlin.test.fail

/**
 * Replays review sequences generated by py-fsrs 6.3.3 (fuzzing off) and checks
 * that the Kotlin port lands on the same state, step, stability, difficulty and due date.
 * The generator is `src/test/resources/fsrs/gen_fsrs_vectors.py`.
 */
class FsrsReferenceTest {

    private fun micros(us: Long): Instant = Instant.EPOCH.plus(us, ChronoUnit.MICROS)

    private fun close(expected: Double, actual: Double, what: String) {
        val tolerance = 1e-9 * maxOf(1.0, abs(expected))
        assertTrue(abs(expected - actual) <= tolerance, "$what: expected $expected, got $actual")
    }

    @Test
    fun matchesPyFsrs() {
        val text = javaClass.getResource("/fsrs/py-fsrs-vectors.json")?.readText() ?: fail("vectors missing")
        val root = Json.parseToJsonElement(text).jsonObject
        val cases = root["cases"]!!.jsonArray
        var checked = 0
        for ((caseIndex, caseElement) in cases.withIndex()) {
            val case = caseElement.jsonObject
            val cfg = case["scheduler"]!!.jsonObject
            val scheduler = FsrsScheduler(
                parameters = cfg["parameters"]!!.jsonArray.map { it.jsonPrimitive.double },
                desiredRetention = cfg["desired_retention"]!!.jsonPrimitive.double,
                learningSteps = cfg["learning_steps_s"]!!.jsonArray.map { Duration.ofSeconds(it.jsonPrimitive.long) },
                relearningSteps = cfg["relearning_steps_s"]!!.jsonArray.map { Duration.ofSeconds(it.jsonPrimitive.long) },
                maximumInterval = cfg["maximum_interval"]!!.jsonPrimitive.int,
                enableFuzzing = false,
            )
            val reviews = case["reviews"]!!.jsonArray.map { it.jsonObject }
            var memory = Memory(due = micros(reviews.first().long("at_us")))
            for ((i, r) in reviews.withIndex()) {
                val where = "case $caseIndex (${case["config"]}) review $i"
                val at = micros(r.long("at_us"))
                close(r.double("retrievability_before"), scheduler.retrievability(memory, at), "$where retrievability")
                memory = scheduler.review(memory, Rating.of(r.int("rating")), at)
                assertEquals(CardState.of(r.int("state")), memory.state, "$where state")
                assertEquals(r["step"]!!.jsonPrimitive.intOrNull, memory.step, "$where step")
                close(r.double("stability"), memory.stability!!, "$where stability")
                close(r.double("difficulty"), memory.difficulty!!, "$where difficulty")
                assertEquals(micros(r.long("due_us")), memory.due, "$where due")
                checked++
            }
        }
        assertTrue(checked > 400, "only $checked reviews checked")
    }

    @Test
    fun fuzzStaysWithinRangeAndIsDeterministic() {
        val scheduler = FsrsScheduler()
        var m = Memory(due = Instant.parse("2026-01-01T08:00:00Z"))
        var t = m.due
        repeat(6) {
            m = scheduler.review(m, Rating.Good, t, fuzz = 0.5)
            t = m.due
        }
        val unfuzzed = FsrsScheduler(enableFuzzing = false)
        val a = scheduler.review(m, Rating.Good, t, fuzz = 0.0)
        val b = scheduler.review(m, Rating.Good, t, fuzz = 0.999)
        val c = scheduler.review(m, Rating.Good, t, fuzz = 0.999)
        val plain = unfuzzed.review(m, Rating.Good, t)
        assertEquals(b, c)
        val days = { x: Memory -> Duration.between(t, x.due).toDays() }
        assertTrue(days(a) <= days(plain) && days(plain) <= days(b), "${days(a)} ${days(plain)} ${days(b)}")
        assertTrue(days(b) - days(a) >= 2, "fuzz range too narrow: ${days(a)}..${days(b)}")
    }

    @Test
    fun wholeDaysRoundDown() {
        val a = Instant.parse("2026-01-01T10:00:00Z")
        assertEquals(0, FsrsScheduler.wholeDaysBetween(a, a.plusSeconds(86_399)))
        assertEquals(1, FsrsScheduler.wholeDaysBetween(a, a.plusSeconds(86_400)))
        assertEquals(-1, FsrsScheduler.wholeDaysBetween(a, a.minusSeconds(1)))
    }

    private fun JsonObject.long(key: String) = this[key]!!.jsonPrimitive.long
    private fun JsonObject.int(key: String) = this[key]!!.jsonPrimitive.int
    private fun JsonObject.double(key: String) = this[key]!!.jsonPrimitive.double
}
